package main

import "fmt"

// **Описание**: Реализуйте функцию `incrementFirst`, которая принимает указатель на слайс целых чисел и увеличивает первый элемент этого слайса на 1 без возврата значения.
//
// **Входные данные**: Встроенный слайс `data := []int{5, 12, 8, 3, 19}`, передаётся в функцию через указатель.
//
// **Выходные данные**: Весь слайс после изменения — пять чисел через пробел в одну строку.
//
// **Ограничения**:
// - Функция должна принимать *[]int и не возвращать значение
// - Изменение первого элемента должно происходить внутри функции через разыменование указателя на слайс
// - Использовать только стандартный пакет fmt

func incrementFirst(s *[]int) {
	(*s)[0] += 1
}

func main() {
	data := []int{5, 12, 8, 3, 19}
	incrementFirst(&data)
	fmt.Println(data)
}
