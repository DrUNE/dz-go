package main

import "fmt"

// **Описание**: Реализуйте функцию `doubleValue`, которая принимает указатель на целое число и удваивает значение по этому указателю без возврата результата.
//
// **Входные данные**: Целое число `n = 7`, переданное в функцию через указатель.
//
// **Выходные данные**: Вывод значения переменной после вызова функции — одно целое число.
//
// **Ограничения**:
// - Функция не должна возвращать значение (тип возврата — отсутствует)
// - Изменение должно происходить через разыменование указателя внутри функции
// - Использовать только стандартный пакет `fmt`
//
// **Примеры**:
// Input: n = 7
// Output: 14
//
// Input: n = 3
// Output: 6

func doubleValue(n *int) {
	*n = *n * 2
}

func main() {
	n := 7
	doubleValue(&n)
	fmt.Println(n)
}
