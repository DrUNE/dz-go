package main

import "fmt"

func main() {
	// **Описание**: Реализуйте программу, которая инициализирует nil-указатель на целое число,
	// проверяет его на nil и только после этого безопасно присваивает ему адрес переменной
	// и выводит значение через разыменование.
	//
	// **Входные данные**: Встроенная переменная score = 42. Указатель объявляется как nil
	// и затем инициализируется адресом переменной score после проверки.
	//
	// **Выходные данные**: Одна строка — значение, полученное через разыменование указателя
	// после безопасной инициализации.
	//
	// **Ограничения**:
	// - Указатель должен быть изначально объявлен как nil (тип *int)
	// - Перед разыменованием обязательна проверка == nil
	// - Использовать только стандартный пакет fmt
	// - Не использовать дополнительные функции — всё в main

	score := 42

	var p *int

	if p == nil {
		p = &score
	}

	fmt.Println(*p)
}
