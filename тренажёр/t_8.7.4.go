package main

import "fmt"

// **Описание**: Реализуйте программу, которая создаёт указатель на переменную и выводит её адрес в памяти.
//
// **Входные данные**: Встроенная переменная `temperature := 36` объявлена в `main`.
//
// **Выходные данные**: Одна строка — адрес переменной `temperature` в памяти (шестнадцатеричный вид, например `0xc000018090`).
//
// **Ограничения**:
// - Объявить указатель через операцию `&`
// - Вывести именно адрес (не значение переменной)
// - Использовать только стандартный пакет `fmt`
// - Всё реализовать в функции `main`

func main() {
	temperature := 36
	p := &temperature

	fmt.Println(p)
}
