package main

import "fmt"

// **Описание**: Реализуйте программу, которая изменяет элемент слайса по индексу через указатель на этот элемент.
//
// **Входные данные**: Встроенный слайс scores := []int{10, 25, 37, 42, 58}.
// Получите указатель на элемент с индексом 2 и установите его значение равным 100 через разыменование.
//
// **Выходные данные**: Весь слайс после изменения — пять чисел через пробел в одну строку.
//
// **Ограничения**:
// - Изменение элемента должно происходить исключительно через разыменование указателя (*p = ...)
// - Нельзя изменять элемент напрямую через индекс (scores[2] = ...)
// - Использовать только стандартный пакет fmt
// - Всё реализовать в функции main
//
// **Примеры**:
// Input: scores := []int{10, 25, 37, 42, 58}, индекс 2, новое значение 100
// Output: 10 25 100 42 58

func main() {
	scores := []int{10, 25, 37, 42, 58}
	p := &scores[2]
	*p = 100

	fmt.Println(scores)
}
